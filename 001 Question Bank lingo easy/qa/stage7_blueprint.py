"""Stage 7: write blueprints/exam_blueprint_v1.json (and config/exam_blueprint_v1.json used by the assembler)."""
import json
import shutil

from assembler.blueprint import CEFR
from .common import *  # noqa: F401,F403


def spec_for(name, level):
    s = {
        "exam_type": name,
        "kind": "mixed-level placement" if level is None else "strictly level-specific assessment",
        "questions": {"total": 79, "listening": 40, "reading": 39},
        "parts": {"listening": 4, "reading": 3},
        "max_parts_per_topic": 1 if level is None else 2,
        "min_distinct_part_types": {"listening": 3, "reading": 2} if level is None else {"listening": 2, "reading": 2},
        "forbidden_pairs_ref": "forbidden_pairs",
    }
    if level is None:
        s["level_counts"] = {"A1": {"min": 3, "max": 6}, "A2": {"min": 8, "max": 16}, "B1": {"min": 12, "max": 22},
                             "B2": {"min": 16, "max": 28}, "C1": {"min": 10, "max": 20}, "C2": {"min": 3, "max": 10}}
        s["target_level"] = None
        s["min_distinct_subskills"] = {"listening": 4, "reading": 4}
        s["max_subskill_share"] = 0.65
        s["require_each_profile_per_skill"] = True
        s["rationale"] = {
            "levels": "Every CEFR level must appear (min 3 questions each, i.e. >=3.8%) and none may dominate (max 35%). Counts need not be equal or bell-shaped. "
                      "3 questions is a floor for presence, NOT enough for a reliable estimate at A1 or C2 (see docs/remaining_risks.md).",
            "profiles": "Each skill must contain a foundation, an intermediate and an advanced part so weak and strong learners both meet answerable and separating items.",
            "topics": "No topic twice: 7 parts, 20+ available topics.",
        }
    else:
        s["level_counts"] = {lv: ({"min": 79, "max": 79} if lv == level else {"min": 0, "max": 0}) for lv in CEFR}
        s["target_level"] = level
        s["min_target_level_share"] = 1.0
        low = level in ("A1", "A2")
        s["min_distinct_subskills"] = {"listening": 1 if low else {"B1": 3, "B2": 4, "C1": 4, "C2": 3}[level], "reading": 2 if low else {"B1": 3, "B2": 4, "C1": 4, "C2": 4}[level]}
        s["max_subskill_share"] = None if low else 0.9
        s["require_each_profile_per_skill"] = False
        s["rationale"] = {
            "levels": "Assumption: the product asks for a strictly level-specific assessment (the bank was built level-pure). Adjacent-level items are NOT allowed. "
                      "If the product wants a target-level-dominant exam with limited adjacent items, relax level_counts and add adjacent-level parts to the bank first.",
            "subskills": ("A1/A2 listening items in the bank are all detail retrieval, so only 1 distinct sub-skill can be required there (bank limitation, not a design choice)."
                          if low else "Sub-skill variety is required up to what the bank can supply."),
        }
    return s


def run():
    bp = {
        "version": "1.0",
        "status": "draft derived from the current bank structure + stated assumptions; needs product-owner sign-off",
        "generated_by": "qa/stage7_blueprint.py",
        "assumptions": [
            "Exam structure stays 4 Listening parts x 10 questions + 3 Reading parts x 13 questions = 79 MCQ (taken from config/blueprint.json parts_per_test/items_per_part).",
            "Level used for blueprint checks is the recorded level.cefr; the heuristic CEFR recommendations (reports/cefr_reassessment.csv) are NOT used because they are unvalidated.",
            "Primary sub-skill comes from config/question_meta_v2.json (generated by qa/stage5_taxonomy.py).",
            "Hard constraints are never relaxed: if no valid exam is found within max_attempts the assembler raises BlueprintError.",
        ],
        "assembly": {"max_attempts": 200, "attempt_seed_policy": "attempt k draws with random.Random(f'{seed}:{k}'); k=0 is the legacy draw", "on_failure": "BlueprintError with per-constraint violation counts"},
        "forbidden_pairs": [],
        "forbidden_pairs_note": "Populate from reports/duplicate_candidates.csv (kind=source or item with similarity>=0.9). The current bank has no such pairs.",
        "exam_types": {"placement": spec_for("placement", None)},
    }
    for lv in CEFR:
        bp["exam_types"][f"assessment_{lv}"] = spec_for(f"assessment_{lv}", lv)
    write_json(OUT / "blueprints" / "exam_blueprint_v1.json", bp)
    shutil.copy(OUT / "blueprints" / "exam_blueprint_v1.json", ROOT / "config" / "exam_blueprint_v1.json")
    print("blueprint written:", list(bp["exam_types"]))


if __name__ == "__main__":
    run()
